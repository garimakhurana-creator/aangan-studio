// Builds agent/system-prompt.md from the template, config/policy.json and
// kb/services.md, so approved lines and thresholds live in exactly one place.
// Run after changing the policy: npm run agent:build

const fs = require('fs');
const path = require('path');
const { loadPolicy } = require('../lib/policy');

const ROOT = path.join(__dirname, '..');

function buildPrompt(policy = loadPolicy()) {
  const vars = {
    ...policy.approved_lines,
    agent_name: policy.agent.name,
    hard_floor_weeks: policy.timeline.hard_floor_weeks,
    localities: [...policy.service_area.pune, ...policy.service_area.pcmc]
      .map(l => l.replace(/\b\w/g, c => c.toUpperCase())).join(', '),
    // Source citations "(services.md)" are for reviewers, not for the caller.
    faq: fs.readFileSync(path.join(ROOT, 'kb', 'faq.md'), 'utf-8')
      .replace(/^# .*\n/, '')
      .replace(/^Every line here is sourced.*\n/m, '')
      .replace(/ \([^)]*(\.md|T\d\d|W\d\d|brief)[^)]*\)/g, ''),
  };
  const template = fs.readFileSync(path.join(__dirname, 'prompt.template.md'), 'utf-8');
  return template.replace(/\{\{(\w+)\}\}/g, (_, k) => {
    if (!(k in vars)) throw new Error(`Template variable {{${k}}} has no value`);
    return vars[k];
  });
}

if (require.main === module) {
  const policy = loadPolicy();
  const out = `<!-- Generated by agent/build.js from prompt.template.md + config/policy.json (${policy.version}). Do not edit by hand. -->\n${buildPrompt(policy)}`;
  fs.writeFileSync(path.join(__dirname, 'system-prompt.md'), out);
  console.log(`agent/system-prompt.md written (${out.length} chars, policy ${policy.version}).`);
}

module.exports = { buildPrompt };
